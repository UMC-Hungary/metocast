struct Crop
{
    uint32_t x, y, width, height;
};

struct Options
{
    std::string command;
    std::string clip;
    std::string sdk;
    std::string pipeline = "metal";
    std::optional<std::string> gamma, gamut;
    std::optional<uint32_t> iso, kelvin;
    std::optional<int16_t> tint;
    std::optional<float> exposure;
    std::optional<uint16_t> highlightRecovery, gamutCompression;
    std::string lutMode = "embedded";
    std::string lutPath;
    std::optional<Crop> crop;
    uint64_t start = 0;
    std::optional<uint64_t> count;
    uint32_t inFlight = 4;
    std::string sidecar;
    // still: the clip's own look (no settings applied), and the widest JPEG wanted.
    bool asRecorded = false;
    uint32_t maxWidth = 1600;
    BlackmagicRawResolutionScale scale = blackmagicRawResolutionScaleFull;
};

[[noreturn]] void Usage()
{
    std::fputs(
        "usage: braw-decode info [--sdk DIR] [--pipeline metal|cpu] [--sidecar FILE] CLIP\n"
        "       braw-decode frames [--sdk DIR] [--pipeline metal|cpu] [--sidecar FILE] [--gamma NAME] [--gamut NAME]\n"
        "                          [--iso N] [--kelvin N] [--tint N] [--exposure STOPS]\n"
        "                          [--highlight-recovery 0|1] [--gamut-compression 0|1]\n"
        "                          [--lut-mode embedded|file|sidecar|none] [--lut FILE.cube]\n"
        "                          [--crop X,Y,W,H] [--start FRAME] [--count FRAMES] CLIP\n"
        "       braw-decode still [the frames settings] [--as-recorded] [--max-width W] --start FRAME CLIP\n"
        "\n"
        "info prints the clip as JSON. frames writes developed frames to stdout as rgb48le\n"
        "(or rgba64le, as info reports), cropped when --crop is given. still writes one frame as\n"
        "a JPEG at most W wide; --as-recorded ignores the settings and keeps the clip's own look.\n"
        "--sidecar applies a .sidecar file (such as one Resolve saved) as if it sat beside the clip.\n",
        stderr);
    std::exit(64);
}

template <typename T>
T ParseNumber(const std::string& text, const char* flag)
{
    std::istringstream stream(text);
    T value{};
    stream >> value;
    if (stream.fail() || ! stream.eof())
        Fail(std::string("invalid ") + flag + ": " + text, 64);
    return value;
}

Options ParseOptions(int argc, const char* argv[])
{
    if (argc < 3)
        Usage();
    Options options;
    options.command = argv[1];
    if (options.command != "info" && options.command != "frames" && options.command != "still")
        Usage();

    for (int i = 2; i < argc; ++i)
    {
        const std::string flag = argv[i];
        if (flag.rfind("--", 0) != 0)
        {
            if (! options.clip.empty())
                Usage();
            options.clip = flag;
            continue;
        }
        if (flag == "--as-recorded")
        {
            options.asRecorded = true;
            continue;
        }
        if (i + 1 >= argc)
            Usage();
        const std::string value = argv[++i];
        if (flag == "--sdk") options.sdk = value;
        else if (flag == "--sidecar") options.sidecar = value;
        else if (flag == "--max-width") options.maxWidth = ParseNumber<uint32_t>(value, "--max-width");
        else if (flag == "--pipeline") options.pipeline = value;
        else if (flag == "--gamma") options.gamma = value;
        else if (flag == "--gamut") options.gamut = value;
        else if (flag == "--iso") options.iso = ParseNumber<uint32_t>(value, "--iso");
        else if (flag == "--kelvin") options.kelvin = ParseNumber<uint32_t>(value, "--kelvin");
        else if (flag == "--tint") options.tint = ParseNumber<int16_t>(value, "--tint");
        else if (flag == "--exposure") options.exposure = ParseNumber<float>(value, "--exposure");
        else if (flag == "--highlight-recovery") options.highlightRecovery = ParseNumber<uint16_t>(value, "--highlight-recovery");
        else if (flag == "--gamut-compression") options.gamutCompression = ParseNumber<uint16_t>(value, "--gamut-compression");
        else if (flag == "--lut-mode") options.lutMode = value;
        else if (flag == "--lut") options.lutPath = value;
        else if (flag == "--start") options.start = ParseNumber<uint64_t>(value, "--start");
        else if (flag == "--count") options.count = ParseNumber<uint64_t>(value, "--count");
        else if (flag == "--crop")
        {
            Crop crop{};
            if (std::sscanf(value.c_str(), "%u,%u,%u,%u", &crop.x, &crop.y, &crop.width, &crop.height) != 4 ||
                crop.width == 0 || crop.height == 0)
                Fail("invalid --crop: " + value, 64);
            options.crop = crop;
        }
        else
            Usage();
    }
    if (options.clip.empty())
        Usage();
    if (options.pipeline != "metal" && options.pipeline != "cpu")
        Fail("--pipeline must be metal or cpu", 64);
    if (options.lutMode != "embedded" && options.lutMode != "file" && options.lutMode != "none" && options.lutMode != "sidecar")
        Fail("--lut-mode must be embedded, file, sidecar or none", 64);
    if (options.lutMode == "file" && options.lutPath.empty())
        Fail("--lut-mode file needs --lut", 64);
    return options;
}

// ── .cube files ──────────────────────────────────────────────────────────────────────────────────

struct Cube
{
    std::string title;
    uint16_t size = 0;
    std::vector<float> data;
};

Cube ReadCube(const std::string& path)
{
    std::ifstream file(path);
    if (! file)
        Fail("cannot open LUT " + path);
    Cube cube;
    std::string line;
    while (std::getline(file, line))
    {
        if (! line.empty() && line.back() == '\r')
            line.pop_back();
        std::istringstream words(line);
        std::string first;
        if (! (words >> first) || first[0] == '#')
            continue;
        if (first == "TITLE")
        {
            const auto open = line.find('"'), close = line.rfind('"');
            if (open != std::string::npos && close > open)
                cube.title = line.substr(open + 1, close - open - 1);
        }
        else if (first == "LUT_3D_SIZE")
        {
            unsigned size = 0;
            words >> size;
            if (size < 2 || size > 256)
                Fail("unsupported LUT_3D_SIZE in " + path);
            cube.size = static_cast<uint16_t>(size);
        }
        else if (first == "LUT_1D_SIZE")
            Fail(path + " is a 1D LUT; a 3D LUT is required");
        else if (first == "DOMAIN_MIN" || first == "DOMAIN_MAX")
        {
            const float expected = first == "DOMAIN_MIN" ? 0.0f : 1.0f;
            float r = -1, g = -1, b = -1;
            words >> r >> g >> b;
            if (r != expected || g != expected || b != expected)
                Fail(path + " uses a domain other than 0..1, which is not supported");
        }
        else
        {
            std::istringstream triple(line);
            float r, g, b;
            if (! (triple >> r >> g >> b))
                Fail("unreadable line in " + path + ": " + line);
            cube.data.insert(cube.data.end(), {r, g, b});
        }
    }
    const size_t expected = static_cast<size_t>(cube.size) * cube.size * cube.size * 3;
    if (cube.size == 0 || cube.data.size() != expected)
        Fail(path + " does not hold a complete 3D LUT");
    return cube;
}

// ── Clip setup ───────────────────────────────────────────────────────────────────────────────────

// Every value the clip offers for `key`, such as its gammas; empty when it offers no list.
std::vector<std::string> ListClipAttribute(IBlackmagicRawClipProcessingAttributes* attributes, BlackmagicRawClipProcessingAttribute key)
{
    uint32_t count = 0;
    bool readOnly = false;
    if (FAILED(attributes->GetClipAttributeList(key, nullptr, &count, &readOnly)) || count == 0)
        return {};
    std::vector<Variant> values(count);
    for (auto& value : values)
        VariantInit(&value);
    std::vector<std::string> texts;
    if (SUCCEEDED(attributes->GetClipAttributeList(key, values.data(), &count, &readOnly)))
        for (uint32_t i = 0; i < count; ++i)
            texts.push_back(VariantText(values[i]).value_or(""));
    for (auto& value : values)
        VariantClear(&value);
    return texts;
}

// The listed value matching `wanted` regardless of case, so `--gamma "blackmagic design film"` works
// and a typo fails with the choices the clip offers.
std::string PickFromList(IBlackmagicRawClipProcessingAttributes* attributes, BlackmagicRawClipProcessingAttribute key,
                         const std::string& wanted, const char* name)
{
    const std::vector<std::string> values = ListClipAttribute(attributes, key);
    if (values.empty())
        return wanted; // no list to check against: SetClipAttribute has the last word
    std::string choices;
    for (const auto& text : values)
    {
        if (EqualsIgnoringCase(text, wanted))
            return text;
        choices += (choices.empty() ? "" : ", ") + text;
    }
    Fail(std::string("unknown ") + name + " \"" + wanted + "\"; the clip offers: " + choices, 65);
}

void SetClipString(IBlackmagicRawClipProcessingAttributes* attributes, BlackmagicRawClipProcessingAttribute key,
                   const std::string& text, const char* name)
{
    CFString value(text);
    Variant variant;
    VariantInit(&variant);
    variant.vt = blackmagicRawVariantTypeString;
    variant.bstrVal = value;
    Check(attributes->SetClipAttribute(key, &variant), std::string("setting ") + name);
}

void SetClipU16(IBlackmagicRawClipProcessingAttributes* attributes, BlackmagicRawClipProcessingAttribute key,
                uint16_t number, const char* name)
{
    Variant variant;
    VariantInit(&variant);
    variant.vt = blackmagicRawVariantTypeU16;
    variant.uiVal = number;
    Check(attributes->SetClipAttribute(key, &variant), std::string("setting ") + name);
}

void ApplyClipOptions(IBlackmagicRawClipProcessingAttributes* attributes, const Options& options)
{
    if (options.gamma)
        SetClipString(attributes, blackmagicRawClipProcessingAttributeGamma,
                      PickFromList(attributes, blackmagicRawClipProcessingAttributeGamma, *options.gamma, "gamma"), "gamma");
    if (options.gamut)
        SetClipString(attributes, blackmagicRawClipProcessingAttributeGamut,
                      PickFromList(attributes, blackmagicRawClipProcessingAttributeGamut, *options.gamut, "gamut"), "gamut");
    if (options.highlightRecovery)
        SetClipU16(attributes, blackmagicRawClipProcessingAttributeHighlightRecovery, *options.highlightRecovery, "highlight recovery");
    if (options.gamutCompression)
        SetClipU16(attributes, blackmagicRawClipProcessingAttributeGamutCompressionEnable, *options.gamutCompression, "gamut compression");
    // The SDK takes any ISO, but only those for the gain the clip was recorded with develop
    // correctly: ISO 800 on a clip shot at 1250 comes out brighter, not darker.
    uint32_t isoCount = 0;
    bool isoReadOnly = false;
    if (options.iso && SUCCEEDED(attributes->GetISOList(nullptr, &isoCount, &isoReadOnly)) && isoCount > 0)
    {
        std::vector<uint32_t> isos(isoCount);
        Check(attributes->GetISOList(isos.data(), &isoCount, &isoReadOnly), "listing ISOs");
        if (std::find(isos.begin(), isos.end(), *options.iso) == isos.end())
            Fail("ISO " + std::to_string(*options.iso) + " isn't available for this clip, which offers ISO " +
                     std::to_string(isos.front()) + "–" + std::to_string(isos.back()) + "; use the exposure to go further",
                 65);
    }

    if (options.lutMode == "file")
    {
        const Cube cube = ReadCube(options.lutPath);
        SafeArrayBound bound = {0, static_cast<uint32_t>(cube.data.size())};
        Variant data;
        VariantInit(&data);
        data.vt = blackmagicRawVariantTypeSafeArray;
        data.parray = SafeArrayCreate(blackmagicRawVariantTypeFloat32, 1, &bound);
        void* storage = nullptr;
        if (data.parray == nullptr || FAILED(SafeArrayAccessData(data.parray, &storage)))
            Fail("could not allocate the LUT");
        std::memcpy(storage, cube.data.data(), cube.data.size() * sizeof(float));
        SafeArrayUnaccessData(data.parray);
        const std::string name = options.lutPath.substr(options.lutPath.find_last_of('/') + 1);
        Check(attributes->SetSidecarPost3DLUT(CFString(name), CFString(cube.title.empty() ? name : cube.title), cube.size, &data),
              "loading the LUT (" + std::to_string(cube.size) + "-point)");
        VariantClear(&data);
    }
    // `sidecar` keeps the LUT a --sidecar file (or the clip's own .sidecar) brought along.
    const char* mode = options.lutMode == "file" || options.lutMode == "sidecar" ? "Sidecar"
                       : options.lutMode == "embedded"                         ? "Embedded"
                                                                               : "Disabled";
    SetClipString(attributes, blackmagicRawClipProcessingAttributePost3DLUTMode,
                  PickFromList(attributes, blackmagicRawClipProcessingAttributePost3DLUTMode, mode, "LUT mode"), "LUT mode");
}

void SetFrameValue(IBlackmagicRawFrameProcessingAttributes* attributes, BlackmagicRawFrameProcessingAttribute key,
                   const Variant& value, const char* name)
{
    Variant copy = value;
    Check(attributes->SetFrameAttribute(key, &copy), std::string("setting ") + name);
}

void ApplyFrameOptions(IBlackmagicRawFrameProcessingAttributes* attributes, const Options& options)
{
    Variant value;
    VariantInit(&value);
    if (options.iso)
    {
        value.vt = blackmagicRawVariantTypeU32;
        value.uintVal = *options.iso;
        SetFrameValue(attributes, blackmagicRawFrameProcessingAttributeISO, value, "ISO");
    }
    if (options.kelvin)
    {
        value.vt = blackmagicRawVariantTypeU32;
        value.uintVal = *options.kelvin;
        SetFrameValue(attributes, blackmagicRawFrameProcessingAttributeWhiteBalanceKelvin, value, "white balance");
    }
    if (options.tint)
    {
        value.vt = blackmagicRawVariantTypeS16;
        value.iVal = *options.tint;
        SetFrameValue(attributes, blackmagicRawFrameProcessingAttributeWhiteBalanceTint, value, "tint");
    }
    if (options.exposure)
    {
        value.vt = blackmagicRawVariantTypeFloat32;
        value.fltVal = *options.exposure;
        SetFrameValue(attributes, blackmagicRawFrameProcessingAttributeExposure, value, "exposure");
    }
}

// ── Decoder ──────────────────────────────────────────────────────────────────────────────────────

// Members are destroyed bottom-up. The codec must go before the Metal device it runs on: the
// other way round crashes in the SDK's Metal teardown after frames have been processed.
struct Decoder
{
    Owned<IBlackmagicRawFactory> factory;
    Owned<IBlackmagicRawPipelineDeviceIterator> devices;
    Owned<IBlackmagicRawPipelineDevice> device;
    Owned<IBlackmagicRaw> codec;
    Owned<IBlackmagicRawConfiguration> configuration;
    Owned<IBlackmagicRawClip> clip;
    BlackmagicRawResourceFormat format = blackmagicRawResourceFormatRGBU16;
};

void LoadFactory(Decoder& decoder, const std::string& sdk)
{
    std::vector<std::string> candidates;
    if (! sdk.empty())
        candidates.push_back(sdk);
    else
        candidates.assign(std::begin(kDefaultSdkPaths), std::end(kDefaultSdkPaths));
    for (const auto& path : candidates)
        if (IBlackmagicRawFactory* factory = CreateBlackmagicRawFactoryInstanceFromPath(CFString(path)))
        {
            *decoder.factory.Out() = factory;
            return;
        }
    Fail("BlackmagicRawAPI.framework not found (install Blackmagic RAW, or pass --sdk)", 69);
}

// The SDK only reads `<clip>.sidecar` beside the clip, and the source must stay untouched, so a
// sidecar from elsewhere goes beside a link to the clip in a folder removed on exit.
std::filesystem::path g_sidecarFolder;

void RemoveSidecarFolder()
{
    std::error_code ignored;
    std::filesystem::remove_all(g_sidecarFolder, ignored);
}

std::string ClipBesideSidecar(const std::string& clip, const std::string& sidecar)
{
    namespace fs = std::filesystem;
    std::string pattern = (fs::temp_directory_path() / "braw-decode.XXXXXX").string();
    if (mkdtemp(pattern.data()) == nullptr)
        Fail("cannot make a folder for the sidecar");
    g_sidecarFolder = pattern;
    std::atexit(RemoveSidecarFolder);
    std::error_code error;
    const fs::path source = fs::canonical(clip, error);
    if (error)
        Fail("cannot open " + clip + ": " + error.message());
    const fs::path link = g_sidecarFolder / source.filename();
    fs::create_symlink(source, link, error);
    if (! error)
        fs::copy_file(sidecar, fs::path(link).replace_extension(".sidecar"), error);
    if (error)
        Fail("cannot use the sidecar " + sidecar + ": " + error.message());
    return link.string();
}

void OpenClip(Decoder& decoder, const Options& options)
{
    LoadFactory(decoder, options.sdk);
    Check(decoder.factory->CreateCodec(decoder.codec.Out()), "creating the codec");

    const BlackmagicRawPipeline pipeline = options.pipeline == "metal" ? blackmagicRawPipelineMetal : blackmagicRawPipelineCPU;
    Check(decoder.factory->CreatePipelineDeviceIterator(pipeline, blackmagicRawInteropNone, decoder.devices.Out()),
          "finding a " + options.pipeline + " device");
    Check(decoder.devices->CreateDevice(decoder.device.Out()), "creating the " + options.pipeline + " device");

    Check(decoder.codec->QueryInterface(IID_IBlackmagicRawConfiguration, reinterpret_cast<void**>(decoder.configuration.Out())),
          "configuring the codec");
    Check(decoder.configuration->SetFromDevice(decoder.device), "configuring the codec for the device");

    uint32_t count = 0;
    Check(decoder.device->GetSupportedResourceFormats(nullptr, &count), "listing output formats");
    std::vector<BlackmagicRawResourceFormat> formats(count);
    Check(decoder.device->GetSupportedResourceFormats(formats.data(), &count), "listing output formats");
    const auto supports = [&](BlackmagicRawResourceFormat wanted) {
        return std::find(formats.begin(), formats.end(), wanted) != formats.end();
    };
    if (supports(blackmagicRawResourceFormatRGBU16))
        decoder.format = blackmagicRawResourceFormatRGBU16;
    else if (supports(blackmagicRawResourceFormatRGBAU16))
        decoder.format = blackmagicRawResourceFormatRGBAU16;
    else
        Fail("the " + options.pipeline + " device offers no 16-bit RGB output");

    const std::string clip = options.sidecar.empty() ? options.clip : ClipBesideSidecar(options.clip, options.sidecar);
    Check(decoder.codec->OpenClip(CFString(clip), decoder.clip.Out()), "opening " + options.clip);
}

const char* PixelFormatName(BlackmagicRawResourceFormat format)
{
    return format == blackmagicRawResourceFormatRGBU16 ? "rgb48le" : "rgba64le";
}

uint32_t BytesPerPixel(BlackmagicRawResourceFormat format)
{
    return format == blackmagicRawResourceFormatRGBU16 ? 6 : 8;
}

// Shared by both commands: completes read and process jobs, and hands finished frames over in order.
class Callback : public IBlackmagicRawCallback
{
public:
    Callback(const Options& options, IBlackmagicRawClipProcessingAttributes* clipAttributes, BlackmagicRawResourceFormat format)
    : m_options(options), m_clipAttributes(clipAttributes), m_format(format) {}

    // `info` reads the first frame's own settings instead of processing it.
    bool readSettingsOnly = false;
    std::map<std::string, std::string> frameSettings;
    std::map<std::string, std::pair<std::string, std::string>> frameRanges;

    void ReadComplete(IBlackmagicRawJob* job, HRESULT result, IBlackmagicRawFrame* frame) override
    {
        const uint64_t index = FrameIndex(job);
        if (FAILED(result))
            return Failed("reading frame " + std::to_string(index), result);

        Owned<IBlackmagicRawFrameProcessingAttributes> attributes;
        if (FAILED(result = frame->CloneFrameProcessingAttributes(attributes.Out())))
            return Failed("reading frame settings", result);

        if (readSettingsOnly)
        {
            const std::pair<const char*, BlackmagicRawFrameProcessingAttribute> keys[] = {
                {"iso", blackmagicRawFrameProcessingAttributeISO},
                {"kelvin", blackmagicRawFrameProcessingAttributeWhiteBalanceKelvin},
                {"tint", blackmagicRawFrameProcessingAttributeWhiteBalanceTint},
                {"exposure", blackmagicRawFrameProcessingAttributeExposure},
            };
            std::lock_guard<std::mutex> lock(m_mutex);
            for (const auto& [name, key] : keys)
            {
                Variant value, low, high;
                VariantInit(&value);
                VariantInit(&low);
                VariantInit(&high);
                if (SUCCEEDED(attributes->GetFrameAttribute(key, &value)))
                    if (auto text = VariantText(value))
                        frameSettings[name] = *text;
                bool readOnly = false;
                if (SUCCEEDED(attributes->GetFrameAttributeRange(key, &low, &high, &readOnly)) && ! readOnly)
                    if (auto min = VariantText(low), max = VariantText(high); min && max)
                        frameRanges[name] = {*min, *max};
                VariantClear(&value);
                VariantClear(&low);
                VariantClear(&high);
            }
            m_done = true;
            m_changed.notify_all();
            return;
        }

        if (! m_options.asRecorded)
            ApplyFrameOptions(attributes, m_options);
        Owned<IBlackmagicRawJob> process;
        if (FAILED(result = frame->SetResourceFormat(m_format)) ||
            FAILED(result = frame->SetResolutionScale(m_options.scale)) ||
            FAILED(result = frame->CreateJobDecodeAndProcessFrame(m_clipAttributes, attributes, process.Out())) ||
            FAILED(result = process->SetUserData(reinterpret_cast<void*>(index))) ||
            FAILED(result = process->Submit()))
            return Failed("processing frame " + std::to_string(index), result);
    }

    void ProcessComplete(IBlackmagicRawJob* job, HRESULT result, IBlackmagicRawProcessedImage* image) override
    {
        const uint64_t index = FrameIndex(job);
        if (FAILED(result))
            return Failed("processing frame " + std::to_string(index), result);
        image->AddRef();
        std::lock_guard<std::mutex> lock(m_mutex);
        m_ready[index] = image;
        m_changed.notify_all();
    }

    // Blocks until `index` is processed; the caller owns (and must Release) the image.
    IBlackmagicRawProcessedImage* Take(uint64_t index)
    {
        std::unique_lock<std::mutex> lock(m_mutex);
        m_changed.wait(lock, [&] { return ! m_error.empty() || m_ready.count(index) != 0; });
        if (! m_error.empty())
            Fail(m_error, 70);
        IBlackmagicRawProcessedImage* image = m_ready[index];
        m_ready.erase(index);
        return image;
    }

    void WaitForSettings()
    {
        std::unique_lock<std::mutex> lock(m_mutex);
        m_changed.wait(lock, [&] { return m_done || ! m_error.empty(); });
        if (! m_error.empty())
            Fail(m_error, 70);
    }

    // WaitForSettings for a frame that may be unreadable: a failed read is the answer.
    bool ReadSucceeded()
    {
        std::unique_lock<std::mutex> lock(m_mutex);
        m_changed.wait(lock, [&] { return m_done || ! m_error.empty(); });
        return m_error.empty();
    }

    void ReadAudioComplete(IBlackmagicRawJob*, HRESULT, IBlackmagicRawAudioBuffer*) override {}
    void DecodeComplete(IBlackmagicRawJob*, HRESULT) override {}
    void TrimProgress(IBlackmagicRawJob*, float) override {}
    void TrimComplete(IBlackmagicRawJob*, HRESULT) override {}
    void SidecarMetadataParseWarning(IBlackmagicRawClip*, CFStringRef, uint32_t, CFStringRef) override {}
    void SidecarMetadataParseError(IBlackmagicRawClip*, CFStringRef, uint32_t, CFStringRef) override {}
    void PreparePipelineComplete(void*, HRESULT) override {}

    HRESULT STDMETHODCALLTYPE QueryInterface(REFIID, LPVOID* out) override
    {
        *out = nullptr;
        return E_NOINTERFACE;
    }
    ULONG STDMETHODCALLTYPE AddRef() override { return 1; }
    ULONG STDMETHODCALLTYPE Release() override { return 1; } // lives on main()'s stack

private:
    static uint64_t FrameIndex(IBlackmagicRawJob* job)
    {
        void* userData = nullptr;
        job->GetUserData(&userData);
        return reinterpret_cast<uint64_t>(userData);
    }

    void Failed(const std::string& what, HRESULT result)
    {
        char code[16];
        std::snprintf(code, sizeof code, "0x%08X", static_cast<unsigned>(result));
        std::lock_guard<std::mutex> lock(m_mutex);
        if (m_error.empty())
            m_error = what + " failed (" + code + ")";
        m_changed.notify_all();
    }

    const Options& m_options;
    IBlackmagicRawClipProcessingAttributes* m_clipAttributes;
    BlackmagicRawResourceFormat m_format;
    std::mutex m_mutex;
    std::condition_variable m_changed;
    std::map<uint64_t, IBlackmagicRawProcessedImage*> m_ready;
    std::string m_error;
    bool m_done = false;
};

void SubmitRead(IBlackmagicRawClip* clip, uint64_t index)
{
    Owned<IBlackmagicRawJob> read;
    Check(clip->CreateJobReadFrame(index, read.Out()), "reading frame " + std::to_string(index));
    Check(read->SetUserData(reinterpret_cast<void*>(index)), "tagging frame " + std::to_string(index));
    Check(read->Submit(), "reading frame " + std::to_string(index)); // the SDK holds a submitted job
}

// ── info ─────────────────────────────────────────────────────────────────────────────────────────

int Info(const Options& options)
{
    Decoder decoder;
    OpenClip(decoder, options);
    IBlackmagicRawClip* clip = decoder.clip;

    uint32_t width = 0, height = 0;
    float frameRate = 0;
    uint64_t frameCount = 0;
    Check(clip->GetWidth(&width), "reading the width");
    Check(clip->GetHeight(&height), "reading the height");
    Check(clip->GetFrameRate(&frameRate), "reading the frame rate");
    Check(clip->GetFrameCount(&frameCount), "reading the frame count");

    CFStringRef timecodeRef = nullptr, cameraRef = nullptr;
    const std::string timecode = SUCCEEDED(clip->GetTimecodeForFrame(0, &timecodeRef)) ? ToStd(timecodeRef) : "";
    const std::string camera = SUCCEEDED(clip->GetCameraType(&cameraRef)) ? ToStd(cameraRef) : "";

    Crop active = {0, 0, width, height};
    Variant origin, size;
    VariantInit(&origin);
    VariantInit(&size);
    if (SUCCEEDED(clip->GetMetadata(CFSTR("crop_origin"), &origin)) && SUCCEEDED(clip->GetMetadata(CFSTR("crop_size"), &size)))
        if (auto o = VariantPair(origin), s = VariantPair(size); o && s && o->first + s->first <= width && o->second + s->second <= height)
            active = {static_cast<uint32_t>(o->first), static_cast<uint32_t>(o->second),
                      static_cast<uint32_t>(s->first), static_cast<uint32_t>(s->second)};
    VariantClear(&origin);
    VariantClear(&size);

    Owned<IBlackmagicRawClipProcessingAttributes> attributes;
    Check(clip->QueryInterface(IID_IBlackmagicRawClipProcessingAttributes, reinterpret_cast<void**>(attributes.Out())),
          "reading clip settings");
    const auto clipText = [&](BlackmagicRawClipProcessingAttribute key) {
        Variant value;
        VariantInit(&value);
        std::string text;
        if (SUCCEEDED(attributes->GetClipAttribute(key, &value)))
            text = VariantText(value).value_or("");
        VariantClear(&value);
        return text;
    };

    Callback callback(options, attributes, decoder.format);
    callback.readSettingsOnly = true;
    Check(decoder.codec->SetCallback(&callback), "setting the callback");
    SubmitRead(clip, 0);
    callback.WaitForSettings();
    decoder.codec->FlushJobs();

    // A recording that ended uncleanly counts frames that were never fully written, and reading
    // them fails (0x8000FFFF), scattered among good ones. The clip's readable part ends at the
    // first such frame in its last two seconds (each read is a whole frame, about 6 MB from the
    // card, so the probe reads no more), so a render can stop decoding there instead of failing
    // at the very end. Damage further in still fails the render.
    const uint64_t kTailFrames = static_cast<uint64_t>(std::ceil(frameRate * 2));
    uint64_t readableFrames = frameCount;
    for (uint64_t index = frameCount > kTailFrames ? frameCount - kTailFrames : 1; index < frameCount; ++index)
    {
        Callback probe(options, attributes, decoder.format);
        probe.readSettingsOnly = true;
        Check(decoder.codec->SetCallback(&probe), "setting the callback");
        SubmitRead(clip, index);
        const bool readable = probe.ReadSucceeded();
        decoder.codec->FlushJobs();
        if (! readable)
        {
            readableFrames = index;
            break;
        }
    }
    decoder.codec->SetCallback(nullptr); // the callback dies before the codec

    std::printf("{\"width\":%u,\"height\":%u,\"frameRate\":%.6g,\"frameCount\":%llu,\"readableFrames\":%llu,", width,
                height, frameRate, static_cast<unsigned long long>(frameCount), static_cast<unsigned long long>(readableFrames));
    std::printf("\"activeArea\":{\"x\":%u,\"y\":%u,\"width\":%u,\"height\":%u},", active.x, active.y, active.width, active.height);
    std::printf("\"startTimecode\":%s,\"camera\":%s,", JsonString(timecode).c_str(), JsonString(camera).c_str());
    std::printf("\"gamma\":%s,\"gamut\":%s,\"colorScienceGen\":%s,",
                JsonString(clipText(blackmagicRawClipProcessingAttributeGamma)).c_str(),
                JsonString(clipText(blackmagicRawClipProcessingAttributeGamut)).c_str(),
                JsonString(clipText(blackmagicRawClipProcessingAttributeColorScienceGen)).c_str());
    std::printf("\"highlightRecovery\":%s,\"gamutCompression\":%s,",
                JsonString(clipText(blackmagicRawClipProcessingAttributeHighlightRecovery)).c_str(),
                JsonString(clipText(blackmagicRawClipProcessingAttributeGamutCompressionEnable)).c_str());
    std::printf("\"lutMode\":%s,\"embeddedLut\":%s,\"sidecarLut\":%s,",
                JsonString(clipText(blackmagicRawClipProcessingAttributePost3DLUTMode)).c_str(),
                JsonString(clipText(blackmagicRawClipProcessingAttributeEmbeddedPost3DLUTTitle)).c_str(),
                JsonString(clipText(blackmagicRawClipProcessingAttributeSidecarPost3DLUTTitle)).c_str());
    std::printf("\"asShot\":{");
    bool first = true;
    for (const auto& [name, value] : callback.frameSettings)
    {
        std::printf("%s%s:%s", first ? "" : ",", JsonString(name).c_str(), JsonString(value).c_str());
        first = false;
    }
    // What the settings may be set to, for the pickers.
    const auto printList = [](const char* name, const std::vector<std::string>& values) {
        std::printf("\"%s\":[", name);
        for (size_t i = 0; i < values.size(); ++i)
            std::printf("%s%s", i ? "," : "", JsonString(values[i]).c_str());
        std::printf("],");
    };
    std::printf("},\"options\":{");
    printList("gammas", ListClipAttribute(attributes, blackmagicRawClipProcessingAttributeGamma));
    printList("gamuts", ListClipAttribute(attributes, blackmagicRawClipProcessingAttributeGamut));
    uint32_t isoCount = 0;
    bool isoReadOnly = false;
    std::vector<uint32_t> isos;
    if (SUCCEEDED(attributes->GetISOList(nullptr, &isoCount, &isoReadOnly)) && isoCount > 0)
    {
        isos.resize(isoCount);
        if (FAILED(attributes->GetISOList(isos.data(), &isoCount, &isoReadOnly)))
            isos.clear();
    }
    std::vector<std::string> isoTexts;
    for (const uint32_t iso : isos)
        isoTexts.push_back(std::to_string(iso));
    printList("isos", isoTexts);
    std::printf("\"ranges\":{");
    first = true;
    for (const auto& [name, range] : callback.frameRanges)
    {
        std::printf("%s%s:[%s,%s]", first ? "" : ",", JsonString(name).c_str(), JsonString(range.first).c_str(),
                    JsonString(range.second).c_str());
        first = false;
    }
    std::printf("}},\"pixelFormat\":\"%s\",\"pipeline\":%s}\n", PixelFormatName(decoder.format), JsonString(options.pipeline).c_str());
    return 0;
}

// ── frames ───────────────────────────────────────────────────────────────────────────────────────

void WriteAll(const uint8_t* data, size_t length)
{
    while (length > 0)
    {
        const ssize_t written = ::write(STDOUT_FILENO, data, length);
        if (written < 0)
        {
            if (errno == EINTR)
                continue;
            Fail(errno == EPIPE ? "the reader closed the output" : std::string("writing frames: ") + std::strerror(errno), 74);
        }
        data += written;
        length -= static_cast<size_t>(written);
    }
}

// Copies a processed Metal buffer to CPU memory. Unified memory makes a shared buffer cheap.
class MetalReadback
{
public:
    explicit MetalReadback(IBlackmagicRawPipelineDevice* device)
    {
        BlackmagicRawPipeline pipeline;
        void* context = nullptr;
        void* queue = nullptr;
        Check(device->GetPipeline(&pipeline, &context, &queue), "reading the Metal queue");
        m_queue = (__bridge id<MTLCommandQueue>)queue;
    }

    // Callers wrap each call in an autorelease pool: a render reads tens of thousands of frames.
    const uint8_t* Read(IBlackmagicRawProcessedImage* image, uint32_t sizeBytes)
    {
        void* resource = nullptr;
        Check(image->GetResource(&resource), "reading a processed frame");
        id<MTLBuffer> source = (__bridge id<MTLBuffer>)resource;
        if (m_staging == nil || m_staging.length < sizeBytes)
            m_staging = [m_queue.device newBufferWithLength:sizeBytes options:MTLResourceStorageModeShared];
        id<MTLCommandBuffer> commands = [m_queue commandBuffer];
        id<MTLBlitCommandEncoder> blit = [commands blitCommandEncoder];
        [blit copyFromBuffer:source sourceOffset:0 toBuffer:m_staging destinationOffset:0 size:sizeBytes];
        [blit endEncoding];
        [commands commit];
        [commands waitUntilCompleted];
        if (commands.status != MTLCommandBufferStatusCompleted)
            Fail("copying a frame from the GPU failed");
        return static_cast<const uint8_t*>(m_staging.contents);
    }

private:
    id<MTLCommandQueue> m_queue = nil;
    id<MTLBuffer> m_staging = nil;
};

int Frames(const Options& options)
{
    std::signal(SIGPIPE, SIG_IGN);
    Decoder decoder;
    OpenClip(decoder, options);
    IBlackmagicRawClip* clip = decoder.clip;

    uint64_t frameCount = 0;
    Check(clip->GetFrameCount(&frameCount), "reading the frame count");
    if (options.start >= frameCount)
        Fail("--start is past the clip's " + std::to_string(frameCount) + " frames", 64);
    const uint64_t end = options.count ? std::min(frameCount, options.start + *options.count) : frameCount;

    Owned<IBlackmagicRawClipProcessingAttributes> attributes;
    Check(clip->CloneClipProcessingAttributes(attributes.Out()), "copying clip settings");
    ApplyClipOptions(attributes, options);

    Callback callback(options, attributes, decoder.format);
    Check(decoder.codec->SetCallback(&callback), "setting the callback");
    std::optional<MetalReadback> metal;
    if (options.pipeline == "metal")
        metal.emplace(decoder.device);

    const uint32_t bytesPerPixel = BytesPerPixel(decoder.format);
    uint64_t submitted = options.start;
    const auto fill = [&](uint64_t written) {
        while (submitted < end && submitted - written < options.inFlight)
            SubmitRead(clip, submitted++);
    };

    for (uint64_t index = options.start; index < end; ++index)
    {
        fill(index);
        IBlackmagicRawProcessedImage* image = callback.Take(index);
        uint32_t width = 0, height = 0, sizeBytes = 0;
        Check(image->GetWidth(&width), "reading a frame's width");
        Check(image->GetHeight(&height), "reading a frame's height");
        Check(image->GetResourceSizeBytes(&sizeBytes), "reading a frame's size");
        const Crop crop = options.crop.value_or(Crop{0, 0, width, height});
        if (crop.x + crop.width > width || crop.y + crop.height > height)
            Fail("--crop does not fit the " + std::to_string(width) + "x" + std::to_string(height) + " frame", 64);
        const size_t rowBytes = static_cast<size_t>(width) * bytesPerPixel;
        if (sizeBytes < rowBytes * height)
            Fail("a processed frame is smaller than expected");

        @autoreleasepool
        {
            const uint8_t* pixels = nullptr;
            if (metal)
                pixels = metal->Read(image, sizeBytes);
            else
            {
                void* resource = nullptr;
                Check(image->GetResource(&resource), "reading a processed frame");
                pixels = static_cast<const uint8_t*>(resource);
            }
            if (crop.x == 0 && crop.width == width)
                WriteAll(pixels + rowBytes * crop.y, rowBytes * crop.height);
            else
                for (uint32_t row = 0; row < crop.height; ++row)
                    WriteAll(pixels + rowBytes * (crop.y + row) + static_cast<size_t>(crop.x) * bytesPerPixel,
                             static_cast<size_t>(crop.width) * bytesPerPixel);
        }
        image->Release();
    }
    decoder.codec->FlushJobs();
    decoder.codec->SetCallback(nullptr); // the callback dies before the codec
    return 0;
}

// ── still ────────────────────────────────────────────────────────────────────────────────────────

// One frame as a JPEG no wider than --max-width, decoded at the smallest SDK scale that still
// covers that width: a preview, not a master.
int Still(Options options)
{
    Decoder decoder;
    OpenClip(decoder, options);
    IBlackmagicRawClip* clip = decoder.clip;

    uint64_t frameCount = 0;
    uint32_t clipWidth = 0;
    Check(clip->GetFrameCount(&frameCount), "reading the frame count");
    Check(clip->GetWidth(&clipWidth), "reading the width");
    if (options.start >= frameCount)
        Fail("--start is past the clip's " + std::to_string(frameCount) + " frames", 64);
    for (const auto& [divisor, scale] : {std::pair{8u, blackmagicRawResolutionScaleEighth},
                                         {4u, blackmagicRawResolutionScaleQuarter},
                                         {2u, blackmagicRawResolutionScaleHalf}})
        if (clipWidth / divisor >= options.maxWidth)
        {
            options.scale = scale;
            break;
        }

    Owned<IBlackmagicRawClipProcessingAttributes> attributes;
    Check(clip->CloneClipProcessingAttributes(attributes.Out()), "copying clip settings");
    if (! options.asRecorded)
        ApplyClipOptions(attributes, options);
    Callback callback(options, attributes, decoder.format);
    Check(decoder.codec->SetCallback(&callback), "setting the callback");
    SubmitRead(clip, options.start);
    IBlackmagicRawProcessedImage* image = callback.Take(options.start);

    uint32_t width = 0, height = 0, sizeBytes = 0;
    Check(image->GetWidth(&width), "reading the frame's width");
    Check(image->GetHeight(&height), "reading the frame's height");
    Check(image->GetResourceSizeBytes(&sizeBytes), "reading the frame's size");
    const size_t rowBytes = static_cast<size_t>(width) * BytesPerPixel(decoder.format);
    if (sizeBytes < rowBytes * height)
        Fail("the processed frame is smaller than expected");

    @autoreleasepool
    {
        std::optional<MetalReadback> metal;
        const uint8_t* pixels = nullptr;
        if (options.pipeline == "metal")
            pixels = metal.emplace(decoder.device).Read(image, sizeBytes);
        else
        {
            void* resource = nullptr;
            Check(image->GetResource(&resource), "reading the processed frame");
            pixels = static_cast<const uint8_t*>(resource);
        }

        // Developed frames are Rec.709-encoded (or the flat log, shown as it is): tag, don't convert.
        CGColorSpaceRef space = CGColorSpaceCreateWithName(kCGColorSpaceITUR_709);
        CGDataProviderRef provider = CGDataProviderCreateWithData(nullptr, pixels, rowBytes * height, nullptr);
        const CGBitmapInfo layout = kCGBitmapByteOrder16Little |
            (decoder.format == blackmagicRawResourceFormatRGBU16 ? kCGImageAlphaNone : kCGImageAlphaNoneSkipLast);
        CGImageRef frame = CGImageCreate(width, height, 16, BytesPerPixel(decoder.format) * 8, rowBytes, space, layout,
                                         provider, nullptr, false, kCGRenderingIntentDefault);
        const size_t outWidth = std::min<size_t>(width, options.maxWidth);
        const size_t outHeight = std::max<size_t>(1, height * outWidth / width);
        CGContextRef context = CGBitmapContextCreate(nullptr, outWidth, outHeight, 8, 0, space,
                                                     kCGImageAlphaNoneSkipLast | kCGBitmapByteOrder32Big);
        if (frame == nullptr || context == nullptr)
            Fail("could not convert the frame to an image");
        CGContextSetInterpolationQuality(context, kCGInterpolationHigh);
        CGContextDrawImage(context, CGRectMake(0, 0, outWidth, outHeight), frame);
        CGImageRef scaled = CGBitmapContextCreateImage(context);

        NSMutableData* jpeg = [NSMutableData data];
        CGImageDestinationRef destination =
            CGImageDestinationCreateWithData((__bridge CFMutableDataRef)jpeg, CFSTR("public.jpeg"), 1, nullptr);
        NSDictionary* properties = @{(__bridge NSString*)kCGImageDestinationLossyCompressionQuality : @0.85};
        CGImageDestinationAddImage(destination, scaled, (__bridge CFDictionaryRef)properties);
        if (! CGImageDestinationFinalize(destination))
            Fail("could not encode the JPEG");
        CFRelease(destination);
        CGImageRelease(scaled);
        CGContextRelease(context);
        CGImageRelease(frame);
        CGDataProviderRelease(provider);
        CGColorSpaceRelease(space);
        WriteAll(static_cast<const uint8_t*>(jpeg.bytes), jpeg.length);
    }
    image->Release();
    decoder.codec->FlushJobs();
    decoder.codec->SetCallback(nullptr); // the callback dies before the codec
    return 0;
}

} // namespace

int main(int argc, const char* argv[])
{
    @autoreleasepool
    {
        const Options options = ParseOptions(argc, argv);
        if (options.command == "info")
            return Info(options);
        return options.command == "still" ? Still(options) : Frames(options);
    }
}
