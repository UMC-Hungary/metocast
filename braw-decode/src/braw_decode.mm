template <typename T>
class Owned
{
public:
    Owned() = default;
    explicit Owned(T* ptr) : m_ptr(ptr) {}
    ~Owned() { if (m_ptr) m_ptr->Release(); }
    Owned(const Owned&) = delete;
    Owned& operator=(const Owned&) = delete;
    T* operator->() const { return m_ptr; }
    operator T*() const { return m_ptr; }
    T** Out() { return &m_ptr; }

private:
    T* m_ptr = nullptr;
};

class CFString
{
public:
    explicit CFString(const std::string& text)
    : m_ref(CFStringCreateWithCString(kCFAllocatorDefault, text.c_str(), kCFStringEncodingUTF8)) {}
    ~CFString() { if (m_ref) CFRelease(m_ref); }
    CFString(const CFString&) = delete;
    CFString& operator=(const CFString&) = delete;
    operator CFStringRef() const { return m_ref; }

private:
    CFStringRef m_ref;
};

std::string ToStd(CFStringRef text)
{
    if (text == nullptr)
        return {};
    const CFIndex length = CFStringGetMaximumSizeForEncoding(CFStringGetLength(text), kCFStringEncodingUTF8) + 1;
    std::vector<char> buffer(static_cast<size_t>(length));
    if (! CFStringGetCString(text, buffer.data(), length, kCFStringEncodingUTF8))
        return {};
    return buffer.data();
}

bool EqualsIgnoringCase(const std::string& a, const std::string& b)
{
    return a.size() == b.size() && strncasecmp(a.c_str(), b.c_str(), a.size()) == 0;
}

std::string JsonString(const std::string& text)
{
    std::string out = "\"";
    for (const unsigned char c : text)
    {
        switch (c)
        {
            case '"': out += "\\\""; break;
            case '\\': out += "\\\\"; break;
            case '\n': out += "\\n"; break;
            case '\r': out += "\\r"; break;
            case '\t': out += "\\t"; break;
            default:
                if (c < 0x20)
                {
                    char escaped[8];
                    std::snprintf(escaped, sizeof escaped, "\\u%04x", c);
                    out += escaped;
                }
                else
                    out += static_cast<char>(c);
        }
    }
    return out + "\"";
}

// Reads a variant as text for `info`, whatever its type.
std::optional<std::string> VariantText(const Variant& value)
{
    switch (value.vt)
    {
        case blackmagicRawVariantTypeString: return ToStd(value.bstrVal);
        case blackmagicRawVariantTypeU8:
        case blackmagicRawVariantTypeU16: return std::to_string(value.uiVal);
        case blackmagicRawVariantTypeS16: return std::to_string(value.iVal);
        case blackmagicRawVariantTypeS32: return std::to_string(value.intVal);
        case blackmagicRawVariantTypeU32: return std::to_string(value.uintVal);
        case blackmagicRawVariantTypeFloat32: return std::to_string(value.fltVal);
        case blackmagicRawVariantTypeFloat64: return std::to_string(value.dblVal);
        default: return std::nullopt;
    }
}

// A two-number metadata value such as `crop_origin`, stored as a float or integer array.
std::optional<std::pair<double, double>> VariantPair(const Variant& value)
{
    if (value.vt != blackmagicRawVariantTypeSafeArray || value.parray == nullptr)
        return std::nullopt;
    SafeArray* array = value.parray;
    BlackmagicRawVariantType type = blackmagicRawVariantTypeEmpty;
    long lower = 0, upper = -1;
    void* data = nullptr;
    if (FAILED(SafeArrayGetVartype(array, &type)) || FAILED(SafeArrayGetLBound(array, 0, &lower)) ||
        FAILED(SafeArrayGetUBound(array, 0, &upper)) || upper - lower + 1 < 2 ||
        FAILED(SafeArrayAccessData(array, &data)))
        return std::nullopt;
    std::optional<std::pair<double, double>> pair;
    switch (type)
    {
        case blackmagicRawVariantTypeFloat32: pair = {static_cast<float*>(data)[0], static_cast<float*>(data)[1]}; break;
        case blackmagicRawVariantTypeU16: pair = {static_cast<uint16_t*>(data)[0], static_cast<uint16_t*>(data)[1]}; break;
        case blackmagicRawVariantTypeU32: pair = {static_cast<uint32_t*>(data)[0], static_cast<uint32_t*>(data)[1]}; break;
        case blackmagicRawVariantTypeS32: pair = {static_cast<int32_t*>(data)[0], static_cast<int32_t*>(data)[1]}; break;
        default: break;
    }
    SafeArrayUnaccessData(array);
    return pair;
}

