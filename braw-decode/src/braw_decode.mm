// ── Errors ─────────────────────────────────────────────────────────────────────────────────────

[[noreturn]] void Fail(const std::string& message, int code = 1)
{
    std::fprintf(stderr, "braw-decode: %s\n", message.c_str());
    std::exit(code);
}

void Check(HRESULT result, const std::string& what)
{
    if (FAILED(result))
    {
        char code[16];
        std::snprintf(code, sizeof code, "0x%08X", static_cast<unsigned>(result));
        Fail(what + " failed (" + code + ")");
    }
}

